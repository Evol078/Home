"""Regenerate local web fonts and the small homepage avatar.

One-time tooling: python -m pip install Pillow 'fonttools[woff]'
Run from the repository root. Existing TTF/CSS files remain the source material.
"""

from concurrent.futures import ThreadPoolExecutor
from io import BytesIO
from pathlib import Path
import re
from urllib.request import urlopen

from fontTools import subset
from fontTools.ttLib import TTFont
from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "public/css/font"
OUTPUT = ROOT / "src/assets/fonts"
OUTPUT.mkdir(parents=True, exist_ok=True)


def font_face(family, filename, codepoints=None):
    ranges = ""
    if codepoints:
        runs = []
        for cp in sorted(codepoints):
            if runs and cp == runs[-1][1] + 1:
                runs[-1][1] = cp
            else:
                runs.append([cp, cp])
        ranges = "  unicode-range: " + ",".join(
            f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}" for start, end in runs
        ) + ";\n"
    return (
        "@font-face {\n"
        f'  font-family: "{family}";\n'
        "  font-style: normal;\n"
        "  font-weight: 400;\n"
        "  font-display: swap;\n"
        f'  src: url("../assets/fonts/{filename}") format("woff2");\n'
        f"{ranges}"
        "}\n"
    )


def write_font(source, filename, codepoints=None):
    font = TTFont(SOURCE / source, recalcTimestamp=False)
    if codepoints is not None:
        options = subset.Options()
        options.recalc_timestamp = False
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=codepoints)
        subsetter.subset(font)
    font.flavor = "woff2"
    font.save(OUTPUT / filename)


# Keep the existing HarmonyOS font slices byte-for-byte, but serve them on our CDN.
harmony_css = (SOURCE / "HarmonyOS_Regular.css").read_text(encoding="utf-8")
urls = re.findall(r"url\(['\"]?(//[^)'\"]+)", harmony_css)


def download_font(url):
    filename = url.rsplit("/", 1)[1]
    target = OUTPUT / filename
    if not target.exists():
        with urlopen("https:" + url, timeout=25) as response:
            data = response.read()
        # Reject an error/HTML response instead of shipping it as a font.
        TTFont(BytesIO(data))
        target.write_bytes(data)
    return url, f"../assets/fonts/{filename}"


with ThreadPoolExecutor(max_workers=8) as pool:
    for original, local in pool.map(download_font, urls):
        harmony_css = harmony_css.replace(original, local)

css = ["/* Generated by scripts/prepare-site-assets.py. */\n", harmony_css]

for family, source in [("Playball", "Playball-Regular.ttf"), ("UnidreamLED", "UnidreamLED.ttf")]:
    filename = source.replace(".ttf", ".woff2")
    write_font(source, filename)
    css.append(font_face(family, filename))

# The homepage's known text is one small subset. All other glyphs remain
# available in disjoint slices, so changing the daily sentence cannot lose text.
text = (ROOT / ".env").read_text(encoding="utf-8")
for directory, suffixes in [(ROOT / "src", {".vue", ".js"}), (ROOT / "public/data", {".json"})]:
    for path in sorted(directory.rglob("*")):
        if path.suffix in suffixes:
            text += path.read_text(encoding="utf-8")
font = TTFont(SOURCE / "LongCang-Regular.ttf")
all_codepoints = set(font.getBestCmap())
common = set(map(ord, text)) & all_codepoints
write_font("LongCang-Regular.ttf", "LongCang-common.woff2", common)
css.append(font_face("Long Cang", "LongCang-common.woff2", common))
remaining = sorted(all_codepoints - common)
for index, start in enumerate(range(0, len(remaining), 64)):
    codepoints = set(remaining[start:start + 64])
    filename = f"LongCang-{index:02}.woff2"
    write_font("LongCang-Regular.ttf", filename, codepoints)
    css.append(font_face("Long Cang", filename, codepoints))

(ROOT / "src/style/fonts.css").write_text("\n".join(css), encoding="utf-8")

avatar = Image.open(ROOT / "public/image/icon/avatar.png").convert("RGBA")
avatar.resize((240, 240), Image.Resampling.LANCZOS).save(
    ROOT / "src/assets/avatar.webp", quality=88, method=6
)
avatar.resize((180, 180), Image.Resampling.LANCZOS).save(ROOT / "src/assets/apple-touch-icon.png", optimize=True)
avatar.save(ROOT / "src/assets/favicon.ico", format="ICO", sizes=[(16, 16), (32, 32), (48, 48)])

print(f"HarmonyOS: {len(urls)} local slices")
print(f"Long Cang: {len(common)} common glyphs + {len(remaining)} in {(len(remaining) + 63) // 64} fallback slices")
print(f"Common font: {(OUTPUT / 'LongCang-common.woff2').stat().st_size} bytes")
print(f"Avatar: {(ROOT / 'src/assets/avatar.webp').stat().st_size} bytes")
